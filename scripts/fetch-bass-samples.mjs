// Fetches the bass samples that fill in below the guitar's lowest note, and writes the map
// unstrung reads them through.
//
// The guitar pack bottoms out at E2 (MIDI 40), which is a guitar's low E. Anything below that had
// no sample at all: every bass track failed to build, and so did a guitar in any drop tuning.
// Black And Blue Basses is the same author, the same CC0 licence and the same recording setup as
// the guitars already bundled, so its "darkblack" bass in its plain "reg" articulation drops in
// beside them. Only the notes below the guitar are taken; from E2 up the guitar samples are used.
//
// THE OCTAVE. Upstream's own .sfz maps place these samples an octave above where they sound,
// because they are written for bass notation, which sounds an octave below what is written. The
// guitar pack does not do this: its maps are at sounding pitch. Measuring the recordings settles
// it -- darkblack_e2 has its fundamental at 41.3 Hz, which is E1, while its map says MIDI 40, E2.
// So every key is shifted down twelve semitones on the way in, and the map this writes is at
// sounding pitch like the guitar's.
//
// Run: node scripts/fetch-bass-samples.mjs
// It is idempotent: files already present are not downloaded again.

import * as fs from 'node:fs/promises';
import * as path from 'node:path';

const REPO = 'sfzinstruments/karoryfer.black-and-blue-basses';
const RAW = `https://raw.githubusercontent.com/${REPO}/main`;

// Bass notation is written an octave above where it sounds, and upstream's maps follow the
// notation. Ours are at sounding pitch, as the guitar's are.
const OCTAVE_CORRECTION = -12;

// The lowest note the bundled guitar covers. Taking the bass strictly below it keeps one sample
// per pitch, so nothing has to decide between two libraries at playback time.
const GUITAR_LOWEST_KEY = 40;

// The velocity tiers unstrung plays. Upstream also records "mp", which nothing here can ask for,
// so it is left behind rather than costing 43 MB in the repository.
const VELOCITIES = ['p', 'mf', 'f'];

const ROOT = path.join(import.meta.dirname, '..', 'src', 'assets', 'samples', 'black-and-blue-bass');
const SAMPLES_DIR = path.join(ROOT, 'Samples', 'darkblack', 'reg');
const MAP_PATH = path.join(ROOT, 'Programs', 'modules', 'maps_black', 'reg.sfz');

async function download(url) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${response.status} ${response.statusText} for ${url}`);
    return Buffer.from(await response.arrayBuffer());
}

/** Regions from one of upstream's per-velocity maps, already corrected to sounding pitch. */
function parseRegions(text) {
    const regions = [];
    for (const block of text.split('<region>').slice(1)) {
        const opcode = name => block.match(new RegExp(`${name}=([^\\s]+)`))?.[1];
        const sample = opcode('sample');
        const centre = Number(opcode('pitch_keycenter') ?? opcode('lokey'));
        if (!sample || !Number.isFinite(centre)) continue;
        regions.push({
            key: centre + OCTAVE_CORRECTION,
            file: sample.split(/[\\/]/).pop(),
            seqPosition: Number(opcode('seq_position') ?? 1),
            seqLength: Number(opcode('seq_length') ?? 1)
        });
    }
    return regions;
}

const wanted = [];
for (const velocity of VELOCITIES) {
    const url = `${RAW}/Programs/maps/darkblack_reg_${velocity}_map.sfz`;
    process.stdout.write(`reading ${path.basename(url)}\n`);
    const regions = parseRegions((await download(url)).toString('latin1'))
        .filter(region => region.key < GUITAR_LOWEST_KEY);
    for (const region of regions) wanted.push({ ...region, velocity });
}

const keys = [...new Set(wanted.map(r => r.key))].sort((a, b) => a - b);
const files = [...new Set(wanted.map(r => r.file))];
console.log(`${keys.length} notes, MIDI ${keys[0]} to ${keys.at(-1)}, in ${files.length} recordings`);

await fs.mkdir(SAMPLES_DIR, { recursive: true });
let fetched = 0, skipped = 0;
for (const file of files) {
    const target = path.join(SAMPLES_DIR, file);
    try {
        await fs.access(target);
        skipped++;
        continue;
    } catch { /* not there yet */ }
    await fs.writeFile(target, await download(`${RAW}/Samples/darkblack/reg/${file}`));
    fetched++;
    if (fetched % 25 === 0) process.stdout.write(`  ${fetched} downloaded\n`);
}
console.log(`downloaded ${fetched}, already present ${skipped}`);

// Written in the shape of the guitar pack's own ord.sfz, so one parser reads both: a region per
// take, sample paths relative to the Programs directory, and the round-robin order kept as
// upstream sequences it.
const lines = [
    '// Generated by scripts/fetch-bass-samples.mjs -- do not edit by hand.',
    '//',
    '// Black And Blue Basses (CC0) by Karoryfer Lecolds, "darkblack" bass, "reg" articulation.',
    '// Source: https://github.com/' + REPO,
    '//',
    '// Keys are twelve semitones below upstream\'s maps, which are written for bass notation and',
    '// so sit an octave above where these recordings actually sound. These are sounding pitch,',
    '// matching the guitar pack beside them.',
    '//',
    `// Only notes below MIDI ${GUITAR_LOWEST_KEY} are here; from there up the guitar samples cover the range.`,
    ''
];
// How many takes each note and velocity actually cycles through. Upstream's per-velocity maps
// leave seq_length off, and writing it out keeps the map readable on its own terms.
const cycleLength = new Map();
for (const region of wanted) {
    const id = `${region.key}:${region.velocity}`;
    cycleLength.set(id, Math.max(cycleLength.get(id) ?? 0, region.seqPosition));
}

for (const region of wanted.sort((a, b) =>
    a.key - b.key || a.velocity.localeCompare(b.velocity) || a.seqPosition - b.seqPosition)) {
    lines.push(
        '<region>',
        // Relative to the Programs directory, which is where the guitar pack's own map resolves
        // from and therefore what the loader passes as the base for both.
        `sample=../Samples/darkblack/reg/${region.file}`,
        `lokey=${region.key}`,
        `hikey=${region.key}`,
        `pitch_keycenter=${region.key}`,
        `seq_length=${cycleLength.get(`${region.key}:${region.velocity}`)}`,
        `seq_position=${region.seqPosition}`,
        ''
    );
}

await fs.mkdir(path.dirname(MAP_PATH), { recursive: true });
await fs.writeFile(MAP_PATH, lines.join('\n'), 'utf8');
console.log(`wrote ${path.relative(process.cwd(), MAP_PATH)} with ${wanted.length} regions`);
